/**
 * Generate `content/frameworks/asd-essentials-cloud.yaml` from the shared Essentials for cloud catalogue.
 *
 *     pnpm essentials:cloud -- --catalogue path/to/cloud.json
 *
 * ASD publishes the cloud chapter only as a web page (https://www.cyber.gov.au/publication/essentials-for-cloud): no
 * OSCAL and no action ids. The Yuma products share one transcription of it (yumaitau/alignr
 * `prisma/seed/essentials/cloud.json`, the same data as yumaitau/GRiCk#473), with provisional `CL.<principle>.x<n>`
 * ids, so a customer using more than one product sees one set of identifiers. This script turns that JSON into a
 * crownguard framework file. When ASD publishes cloud OSCAL, replace this with a generator like `build.ts`.
 *
 * The chapter is © Commonwealth of Australia 2026, licensed CC BY 4.0 (Coat of Arms and ASD logo excepted).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { z } from "zod";
import { cliArgs, isMain } from "../lib/cli";
import { repoPath } from "../lib/repo";
import { shorten } from "../lib/text";
import { inlineList as list, quoted } from "../lib/yaml-text";

const domainKey = z.enum(["GC", "VR", "BS", "IS", "CPS", "PE", "BUS", "UD"]);
const marker = z.enum(["C", "S", "P"]).nullable();

export const cloudCatalogueSchema = z.looseObject({
  chapter: z.literal("cloud"),
  version: z.string(),
  source: z.url(),
  idScheme: z.literal("provisional"),
  retrievedAt: z.string(),
  expected: z.looseObject({ domains: z.number(), principles: z.number(), actions: z.number() }),
  domains: z.array(z.looseObject({ key: domainKey, name: z.string(), type: z.enum(["capability", "technical"]) })),
  phases: z.array(z.looseObject({ phase: z.enum(["P1", "P2", "P3"]), domains: z.array(domainKey) })),
  principles: z.array(z.looseObject({ key: z.string().regex(/^[A-Z]{3}-\d{2}$/), name: z.string() })),
  actions: z.array(
    z.looseObject({
      id: z.string().regex(/^CL\.[A-Z]{3}-\d{2}\.x\d+$/),
      principle: z.string(),
      statement: z.string(),
      domains: z.array(domainKey).min(1),
      provisional: z.literal(true),
      sharedResponsibility: z.looseObject({ paas: marker, saas: marker }).nullable(),
    }),
  ),
});
type CloudCatalogue = z.infer<typeof cloudCatalogueSchema>;

export function cloudYaml(c: CloudCatalogue): string {
  const { expected } = c;
  if (c.domains.length !== expected.domains || c.principles.length !== expected.principles || c.actions.length !== expected.actions)
    throw new Error(`catalogue counts ${c.domains.length}/${c.principles.length}/${c.actions.length} don't match expected ${expected.domains}/${expected.principles}/${expected.actions}`);
  const principleName = new Map(c.principles.map((p) => [p.key, p.name]));
  const phasesOf = (key: string, type: string) =>
    type === "capability" ? [1, 2, 3] : c.phases.filter((p) => p.domains.includes(key as never)).map((p) => Number(p.phase.slice(1)));
  const lines = [
    "# Generated by scripts/essentials/cloud.ts from the shared Essentials for cloud catalogue. Do not edit by hand.",
    `# Transcribed from ${c.source} (retrieved ${c.retrievedAt}). ASD has published no action ids or OSCAL`,
    "# for this chapter, so every id is provisional (CL.<principle>.x<n>), matching the Yuma shared catalogue.",
    "# © Commonwealth of Australia 2026, licensed CC BY 4.0 (Coat of Arms and ASD logo excepted).",
    "id: asd-essentials-cloud",
    "name: ASD Essentials for cloud",
    "shortName: Essentials (cloud)",
    "publisher: Australian Signals Directorate",
    "source: asd-essentials-cloud",
    "sources: [asd-essentials-assessment-process, asd-essentials-transition, asd-essentials-what, asd-essentials-faq, asd-essentials-cloud-scoping]",
    "closed: true",
    "note: >-",
    "  ASD's Essentials for cloud is the chapter for organisations running entirely on SaaS and PaaS. ASD has not",
    "  published action ids, Indicators of Good Practice or OSCAL for it, so the ids here are provisional and will",
    "  change when ASD publishes its own. `responsibility` is ASD's shared responsibility marker for PaaS and SaaS:",
    "  C Customer, S Supplied, P Provider-inherited. Results are indicative and never derived from Essential Eight",
    "  maturity levels. © Commonwealth of Australia 2026, licensed CC BY 4.0 (Coat of Arms and ASD logo excepted),",
    "  shortened and reformatted by crownguard.",
    "essentials:",
    "  chapter: cloud",
    `  release: ${quoted(c.version)}`,
    "  provisional: true",
    "  domains:",
    ...c.domains.map((d) => `    - { id: ${d.key}, name: ${quoted(d.name)}, type: ${d.type}, phases: ${list(phasesOf(d.key, d.type))} }`),
    "  principles:",
    ...c.principles.map((p) => `    - { id: ${p.key}, name: ${quoted(p.name)} }`),
    "controls:",
  ];
  for (const a of c.actions) {
    const name = principleName.get(a.principle);
    if (!name) throw new Error(`${a.id}: unknown principle ${a.principle}`);
    lines.push(`  - id: ${a.id}`);
    lines.push(`    principle: ${a.principle}`);
    lines.push(`    group: ${quoted(`${a.principle} ${name}`)}`);
    lines.push(`    title: ${quoted(shorten(a.statement.replace(/\s+/g, " ")))}`);
    lines.push(`    domains: ${list(a.domains)}`);
    const r = a.sharedResponsibility;
    const parts = [r?.paas ? `paas: ${r.paas}` : "", r?.saas ? `saas: ${r.saas}` : ""].filter(Boolean);
    if (parts.length) lines.push(`    responsibility: { ${parts.join(", ")} }`);
  }
  return `${lines.join("\n")}\n`;
}

function main() {
  const { values } = parseArgs({ args: cliArgs(), options: { catalogue: { type: "string" } } });
  if (!values.catalogue) {
    console.error("usage: pnpm essentials:cloud -- --catalogue path/to/cloud.json");
    process.exit(1);
  }
  const parsed = cloudCatalogueSchema.safeParse(JSON.parse(readFileSync(values.catalogue, "utf8")));
  if (!parsed.success) {
    console.error(parsed.error.issues.slice(0, 10).map((i) => `${i.path.join(".")}: ${i.message}`).join("\n"));
    process.exit(1);
  }
  const out = repoPath("content", "frameworks", "asd-essentials-cloud.yaml");
  writeFileSync(out, cloudYaml(parsed.data));
  console.log(`${out}: ${parsed.data.actions.length} actions`);
}

if (isMain(import.meta.url)) main();
