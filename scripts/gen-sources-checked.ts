/**
 * Writes the tiny `SOURCES_LAST_CHECKED` constant from `watch/state.json` so the client bundle never ships the whole
 * baseline. Uses the newest feed cursor date in the state file, then the git date of that file.
 */
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { isMain } from "./lib/cli";
import { ISO_DATE } from "../src/format/vocab";
import { repoPath, ROOT } from "./lib/repo";
import { readState } from "./watch/apply";
import type { WatchState } from "./watch/types";

const OUT_PATH = join("src", "content", "sourcesChecked.ts");
const STATE_PATH = join("watch", "state.json");

/** Newest feed cursor date, ignoring any dated more than a day after `now` (a future-dated feed entry is a mistake). */
export function newestFeedDate(state: Pick<WatchState, "feeds">, now: number = Date.now()): string | undefined {
  const horizon = new Date(now + 86_400_000).toISOString().slice(0, 10);
  const feedDates = Object.values(state.feeds)
    .map((f) => f.latest.slice(0, 10))
    .filter((d) => ISO_DATE.test(d) && d <= horizon)
    .sort()
    .reverse();
  return feedDates[0];
}

function fromGit(): string | undefined {
  try {
    const d = execSync(`git log -1 --format=%cs -- ${STATE_PATH}`, { cwd: ROOT, encoding: "utf8" }).trim();
    return ISO_DATE.test(d) ? d : undefined;
  } catch {
    // Not a git checkout (a source tarball): the date is unknown.
    return undefined;
  }
}

function sourcesLastChecked(): string {
  const path = repoPath(STATE_PATH);
  return (existsSync(path) ? newestFeedDate(readState(path)) : undefined) ?? fromGit() ?? "unknown";
}

function sourcesCheckedText(date: string): string {
  return `/** YYYY-MM-DD the committed source-watch baseline was last updated. Generated by scripts/gen-sources-checked.ts — do not edit. */\nexport const SOURCES_LAST_CHECKED: string = ${JSON.stringify(date)};\n`;
}

if (isMain(import.meta.url)) {
  const date = sourcesLastChecked();
  mkdirSync(dirname(repoPath(OUT_PATH)), { recursive: true });
  writeFileSync(repoPath(OUT_PATH), sourcesCheckedText(date));
  console.log(`wrote ${OUT_PATH} (${date})`);
}
